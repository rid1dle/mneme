import CryptoKit
import Foundation

/// What the pasteboard held at one change: its types and, per pasteboard item, the bytes of each type read.
public struct PasteboardSnapshot: Sendable {
    public var changeCount: Int
    public var types: [String]
    public var items: [[String: Data]]
    public init(changeCount: Int, types: [String], items: [[String: Data]]) {
        self.changeCount = changeCount; self.types = types; self.items = items
    }
}

public struct CaptureRules: Sendable {
    public static let defaultExcluded: Set<String> = [
        "com.1password.1password", "com.agilebits.onepassword7", "com.apple.keychainaccess", "com.apple.Passwords",
    ]
    public var excludedBundleIDs: Set<String> = CaptureRules.defaultExcluded
    public var kinds: Set<ItemKind> = Set(ItemKind.allCases)
    public var maxBytes = 50_000_000
    public var ownChangeCount: Int?
    public var paused = false
    /// Every app that was in front since the last check: a copy made in an excluded app and followed by a quick
    /// switch to another app is still skipped.
    public var recentBundleIDs: Set<String> = []
    public init() {}
}

public enum SkipReason: Error, Equatable {
    case paused, ownWrite, concealed, transient, autoGenerated, excludedApp, kindOff, tooLarge, empty
}

public struct Capture: Sendable {
    public var kind: ItemKind
    public var text: String?
    public var preview: String
    public var representations: [Representation]
    public var fileURLs: [URL]
    public var source: SourceApp?
    public var hash: String
    public var byteSize: Int
}

public let ownMarkerType = "local.mneme.own"

public enum PasteType {
    public static let plain = "public.utf8-plain-text"
    public static let rtf = "public.rtf"
    public static let rtfd = "com.apple.flat-rtfd"
    public static let html = "public.html"
    public static let png = "public.png"
    public static let tiff = "public.tiff"
    public static let fileURL = "public.file-url"
    public static let url = "public.url"
    public static let concealed = "org.nspasteboard.ConcealedType"
    public static let transient = "org.nspasteboard.TransientType"
    public static let autoGenerated = "org.nspasteboard.AutoGeneratedType"
    static let images: Set<String> = [png, tiff, "public.jpeg", "public.heic", "com.compuserve.gif"]
    static let rich: Set<String> = [rtf, rtfd, html]
    static let markers: Set<String> = [concealed, transient, autoGenerated, ownMarkerType]
}

/// Legacy aliases (`NSStringPboardType`, "Apple HTML pasteboard type"), dynamic `dyn.` types and marker types are
/// derived or meaningless when pasted back, so only real UTIs are kept.
func isKeptType(_ t: String) -> Bool {
    !(t.hasPrefix("dyn.") || t.contains(" ") || (t.hasPrefix("NS") && t.hasSuffix("PboardType")) || PasteType.markers.contains(t))
}

public let previewLength = 300

public func classify(_ s: PasteboardSnapshot, source: SourceApp?, rules: CaptureRules) -> Result<Capture, SkipReason> {
    if rules.paused { return .failure(.paused) }
    let types = Set(s.types).union(s.items.flatMap(\.keys))
    if types.contains(ownMarkerType) || rules.ownChangeCount == s.changeCount { return .failure(.ownWrite) }
    if types.contains(PasteType.concealed) { return .failure(.concealed) }
    if types.contains(PasteType.transient) { return .failure(.transient) }
    if types.contains(PasteType.autoGenerated) { return .failure(.autoGenerated) }
    if let id = source?.bundleID, rules.excludedBundleIDs.contains(id) { return .failure(.excludedApp) }
    if !rules.recentBundleIDs.isDisjoint(with: rules.excludedBundleIDs) { return .failure(.excludedApp) }

    var reps: [Representation] = []
    for (i, item) in s.items.enumerated() {
        let dropTiff = item[PasteType.png] != nil
        for (type, data) in item where isKeptType(type) && !(dropTiff && type == PasteType.tiff) {
            reps.append(Representation(index: i, type: type, data: data))
        }
    }
    reps.sort { ($0.index, $0.type) < ($1.index, $1.type) }
    let byteSize = reps.reduce(0) { $0 + $1.data.count }
    if byteSize == 0 { return .failure(.empty) }
    if byteSize > rules.maxBytes { return .failure(.tooLarge) }

    let first = s.items.first ?? [:]
    let plain = first[PasteType.plain].flatMap { String(data: $0, encoding: .utf8) }
    let fileURLs = s.items.compactMap { $0[PasteType.fileURL].flatMap { String(data: $0, encoding: .utf8) }.flatMap(URL.init(string:)) }
        .filter(\.isFileURL)
    let kept = Set(reps.map(\.type))

    var kind: ItemKind
    var text = plain
    var preview: String
    if fileURLs.count == 1, isImageFile(fileURLs[0]) {
        kind = .image
        text = fileURLs[0].path
        preview = fileURLs[0].lastPathComponent
    } else if !fileURLs.isEmpty {
        kind = .file
        text = fileURLs.map(\.path).joined(separator: "\n")
        preview = fileURLs.map(\.lastPathComponent).joined(separator: ", ")
    } else if !kept.isDisjoint(with: PasteType.images) {
        kind = .image
        text = nil
        preview = "Image"
    } else if let p = plain, let color = parseColor(p) {
        kind = .color
        text = p.trimmingCharacters(in: .whitespacesAndNewlines)
        preview = color
    } else if let link = loneLink(plain ?? first[PasteType.url].flatMap { String(data: $0, encoding: .utf8) }) {
        kind = .link
        text = link
        preview = link
    } else if !kept.isDisjoint(with: PasteType.rich) {
        kind = .richText
        preview = String((plain ?? "Rich text").prefix(previewLength))
    } else {
        kind = .text
        preview = String((plain ?? "").prefix(previewLength))
    }
    if !rules.kinds.contains(kind) { return .failure(.kindOff) }

    return .success(Capture(kind: kind, text: text, preview: preview, representations: reps, fileURLs: fileURLs,
                            source: source, hash: contentHash(reps), byteSize: byteSize))
}

/// SHA-256 over the representations in (item, type) order, as lowercase hex.
public func contentHash(_ reps: [Representation]) -> String {
    var hasher = SHA256()
    for r in reps.sorted(by: { ($0.index, $0.type) < ($1.index, $1.type) }) {
        hasher.update(data: Data("\(r.index):\(r.type)".utf8) + Data([0]))
        hasher.update(data: r.data)
    }
    return hasher.finalize().map { String(format: "%02x", $0) }.joined()
}

private let imageExtensions: Set<String> = ["png", "jpg", "jpeg", "heic", "heif", "gif", "tif", "tiff", "webp", "bmp"]

/// One copied image file (a CleanShot screenshot, an image copied in Finder) is shown and searched as an image.
public func isImageFile(_ url: URL) -> Bool { imageExtensions.contains(url.pathExtension.lowercased()) }

/// The whole string, trimmed, is one http(s) address.
func loneLink(_ s: String?) -> String? {
    guard let t = s?.trimmingCharacters(in: .whitespacesAndNewlines), !t.isEmpty,
          !t.contains(where: { $0.isWhitespace }),
          let url = URL(string: t), let scheme = url.scheme?.lowercased(), scheme == "http" || scheme == "https",
          url.host?.isEmpty == false else { return nil }
    return t
}

/// A string that is only a CSS-style color (`#rgb`, `#rgba`, `#rrggbb`, `#rrggbbaa`, `rgb()`, `rgba()`, `hsl()`,
/// `hsla()`), normalized to `#RRGGBB` (or `#RRGGBBAA` when not opaque).
public func parseColor(_ input: String) -> String? {
    let s = input.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
    if s.hasPrefix("#") {
        let hex = Array(s.dropFirst())
        guard [3, 4, 6, 8].contains(hex.count), hex.allSatisfy(\.isHexDigit) else { return nil }
        let full = hex.count <= 4 ? hex.flatMap { [$0, $0] } : hex
        var out = "#" + String(full).uppercased()
        if out.count == 9, out.hasSuffix("FF") { out.removeLast(2) }
        return out
    }
    guard let open = s.firstIndex(of: "("), s.hasSuffix(")") else { return nil }
    let fn = String(s[..<open]).trimmingCharacters(in: .whitespaces)
    let parts = s[s.index(after: open)..<s.index(before: s.endIndex)]
        .split(whereSeparator: { $0 == "," || $0 == " " || $0 == "/" }).map(String.init)
    guard parts.count == 3 || parts.count == 4 else { return nil }
    func number(_ p: String, percentOf scale: Double) -> Double? {
        if p.hasSuffix("%") { return Double(p.dropLast()).map { $0 / 100 * scale } }
        return Double(p)
    }
    let alpha: Double
    if parts.count == 4 { guard let a = number(parts[3], percentOf: 1) else { return nil }; alpha = a } else { alpha = 1 }
    var rgb: (Double, Double, Double)
    switch fn {
    case "rgb", "rgba":
        guard let r = number(parts[0], percentOf: 255), let g = number(parts[1], percentOf: 255), let b = number(parts[2], percentOf: 255) else { return nil }
        rgb = (r / 255, g / 255, b / 255)
    case "hsl", "hsla":
        guard let h = Double(parts[0].replacingOccurrences(of: "deg", with: "")),
              parts[1].hasSuffix("%"), parts[2].hasSuffix("%"),
              let sat = number(parts[1], percentOf: 1), let l = number(parts[2], percentOf: 1) else { return nil }
        let c = (1 - abs(2 * l - 1)) * sat
        let hp = (h.truncatingRemainder(dividingBy: 360) + 360).truncatingRemainder(dividingBy: 360) / 60
        let x = c * (1 - abs(hp.truncatingRemainder(dividingBy: 2) - 1))
        let m = l - c / 2
        let (r1, g1, b1): (Double, Double, Double) = switch Int(hp) {
        case 0: (c, x, 0)
        case 1: (x, c, 0)
        case 2: (0, c, x)
        case 3: (0, x, c)
        case 4: (x, 0, c)
        default: (c, 0, x)
        }
        rgb = (r1 + m, g1 + m, b1 + m)
    default: return nil
    }
    func byte(_ v: Double) -> Int { Int((min(max(v, 0), 1) * 255).rounded()) }
    var out = String(format: "#%02X%02X%02X", byte(rgb.0), byte(rgb.1), byte(rgb.2))
    if alpha < 1 { out += String(format: "%02X", byte(alpha)) }
    return out
}
