import Foundation

private let plain = "public.utf8-plain-text"
private let png = Data([0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A]) + Data(repeating: 1, count: 64)
private func snap(_ data: [String: Data], extraTypes: [String] = [], count: Int = 1) -> PasteboardSnapshot {
    PasteboardSnapshot(changeCount: count, types: Array(data.keys) + extraTypes, items: [data])
}
private func text(_ s: String) -> PasteboardSnapshot { snap([plain: Data(s.utf8)]) }
private var rules: CaptureRules { CaptureRules() }
private let safari = SourceApp(bundleID: "com.apple.Safari", name: "Safari")

private func kind(_ s: PasteboardSnapshot, _ r: CaptureRules = CaptureRules()) -> ItemKind? {
    if case .success(let c) = classify(s, source: safari, rules: r) { return c.kind }
    return nil
}
private func skip(_ s: PasteboardSnapshot, source: SourceApp? = safari, _ r: CaptureRules = CaptureRules()) -> SkipReason? {
    if case .failure(let why) = classify(s, source: source, rules: r) { return why }
    return nil
}
private func capture(_ s: PasteboardSnapshot) -> Capture? {
    if case .success(let c) = classify(s, source: safari, rules: CaptureRules()) { return c }
    return nil
}

let captureTests: [TestCase] = [
    test("should skip anything a password manager marks as concealed") {
        expectEqual(skip(snap([plain: Data("hunter2".utf8)], extraTypes: ["org.nspasteboard.ConcealedType"])), .concealed)
    },
    test("should skip transient and auto-generated copies") {
        expectEqual(skip(snap([plain: Data("a".utf8)], extraTypes: ["org.nspasteboard.TransientType"])), .transient)
        expectEqual(skip(snap([plain: Data("a".utf8)], extraTypes: ["org.nspasteboard.AutoGeneratedType"])), .autoGenerated)
    },
    test("should skip copies made in an excluded app") {
        expectEqual(skip(text("secret"), source: SourceApp(bundleID: "com.1password.1password", name: "1Password")), .excludedApp)
        expect(CaptureRules.defaultExcluded.contains("com.apple.keychainaccess"))
        expect(CaptureRules.defaultExcluded.contains("com.apple.Passwords"))
    },
    test("should skip Mneme's own writes") {
        expectEqual(skip(snap([plain: Data("a".utf8), ownMarkerType: Data()])), .ownWrite)
        var r = CaptureRules(); r.ownChangeCount = 7
        expectEqual(skip(snap([plain: Data("a".utf8)], count: 7), r), .ownWrite)
    },
    test("should skip everything while paused") {
        var r = CaptureRules(); r.paused = true
        expectEqual(skip(text("a"), r), .paused)
    },
    test("should skip a copy larger than the size cap") {
        expectEqual(skip(snap(["public.png": Data(count: 60_000_000)])), .tooLarge)
    },
    test("should skip a copy that lists types but carries no data") {
        expectEqual(skip(PasteboardSnapshot(changeCount: 1, types: [plain], items: [[:]])), .empty)
        expectEqual(skip(text("")), .empty)
    },
    test("should classify plain text and keep a short preview") {
        let big = String(repeating: "word ", count: 1_000_000)
        let c = capture(text(big))
        expectEqual(c?.kind, .text)
        expect((c?.preview.count ?? 999) <= 300, "preview \(c?.preview.count ?? -1)")
        expectEqual(c?.text?.count, big.count)
    },
    test("should classify rich text and keep the plain text beside it") {
        let c = capture(snap(["public.rtf": Data("{\\rtf1 hi}".utf8), plain: Data("hi".utf8)]))
        expectEqual(c?.kind, .richText)
        expectEqual(c?.text, "hi")
        expectEqual(Set(c?.representations.map(\.type) ?? []), ["public.rtf", plain])
    },
    test("should classify a lone web address as a link") {
        expectEqual(kind(text("  https://example.com/a?b=1 \n")), .link)
        expectEqual(capture(text("  https://example.com/a?b=1 \n"))?.text, "https://example.com/a?b=1")
    },
    test("should not classify a sentence containing a link as a link") {
        expectEqual(kind(text("see https://example.com now")), .text)
    },
    test("should classify a hex or rgb string as a color") {
        expectEqual(parseColor("#3a7"), "#33AA77")
        expectEqual(parseColor("rgb(58, 112, 200)"), "#3A70C8")
        expectEqual(parseColor("hsl(0,100%,50%)"), "#FF0000")
        expectEqual(parseColor("#3a7 is nice"), nil)
        expectEqual(kind(text(" #3A70C8 ")), .color)
    },
    test("should classify an image") {
        expectEqual(kind(snap(["public.png": png])), .image)
    },
    test("should keep only the png when an image comes as png and tiff") {
        let c = capture(snap(["public.png": png, "public.tiff": Data(count: 500)]))
        expectEqual(c?.representations.map(\.type), ["public.png"])
    },
    test("should classify files as references") {
        let s = PasteboardSnapshot(changeCount: 1, types: ["public.file-url"], items: [
            ["public.file-url": Data("file:///Users/me/a.pdf".utf8)],
            ["public.file-url": Data("file:///Users/me/b%20c.txt".utf8)],
        ])
        let c = capture(s)
        expectEqual(c?.kind, .file)
        expectEqual(c?.fileURLs.map(\.path), ["/Users/me/a.pdf", "/Users/me/b c.txt"])
        expectEqual(c?.preview, "a.pdf, b c.txt")
    },
    test("should treat one copied image file as an image, the way CleanShot and Finder copy screenshots") {
        let s = PasteboardSnapshot(changeCount: 1, types: ["public.file-url", "public.png"], items: [[
            "public.file-url": Data("file:///var/folders/x/CleanShot%202026-11-25%20at%2023.41.32@2x.png".utf8), "public.png": png]])
        let c = capture(s)
        expectEqual(c?.kind, .image)
        expectEqual(c?.fileURLs.map(\.lastPathComponent), ["CleanShot 2026-11-25 at 23.41.32@2x.png"])
        expectEqual(c?.preview, "CleanShot 2026-11-25 at 23.41.32@2x.png")
        expectEqual(Set(c?.representations.map(\.type) ?? []), ["public.file-url", "public.png"])
    },
    test("should keep several image files as files") {
        let s = PasteboardSnapshot(changeCount: 1, types: ["public.file-url"], items: [
            ["public.file-url": Data("file:///tmp/a.png".utf8)], ["public.file-url": Data("file:///tmp/b.jpg".utf8)]])
        expectEqual(capture(s)?.kind, .file)
    },
    test("should keep one file that is not an image as a file even when an icon comes with it") {
        let s = PasteboardSnapshot(changeCount: 1, types: ["public.file-url", "public.png"], items: [[
            "public.file-url": Data("file:///tmp/report.pdf".utf8), "public.png": png]])
        expectEqual(capture(s)?.kind, .file)
    },
    test("should drop legacy and private duplicate types") {
        let c = capture(snap([plain: Data("a b".utf8), "NSStringPboardType": Data("a b".utf8), "dyn.ah62d4rv4gu8y": Data([1]),
                              "Apple HTML pasteboard type": Data([1])]))
        expectEqual(c?.representations.map(\.type), [plain])
    },
    test("should give the same hash to the same content regardless of type order") {
        let a = PasteboardSnapshot(changeCount: 1, types: ["public.rtf", plain], items: [["public.rtf": Data("r".utf8), plain: Data("p".utf8)]])
        let b = PasteboardSnapshot(changeCount: 2, types: [plain, "public.rtf"], items: [[plain: Data("p".utf8), "public.rtf": Data("r".utf8)]])
        expectEqual(capture(a)?.hash, capture(b)?.hash)
        expectEqual(capture(a)?.hash.count, 64)
    },
    test("should give different hashes to different content") {
        expect(capture(text("one"))?.hash != capture(text("two"))?.hash)
    },
    test("should skip a kind the user turned off") {
        var r = CaptureRules(); r.kinds.remove(.image)
        expectEqual(skip(snap(["public.png": png]), r), .kindOff)
    },
]
